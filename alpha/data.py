def verify(config_path: str):
    manager = DatasetManager(config_path)
    datasets = manager.config['datasets']
    print(f"Found {len(datasets)} datasets in configuration.")
    for idx, name in enumerate(datasets):
        print(f"Verifying dataset {idx + 1}/{len(datasets)}: {name}")
        try:
            dataset = manager._load_dataset(name)
            # print in cyan
            print(f"  \033[96mDataset {name} loaded successfully with {len(dataset)} samples.\033[0m")
            del dataset
            del manager.cache[name]
        except Exception as e:
            # print in red
            print(f"  \033[91mFailed to load dataset {name}: {e}\033[0m")

